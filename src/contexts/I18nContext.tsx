type TranslationKeys = keyof typeof translations.en;

interface I18nContextValue {
  lang: Language;
  dir: 'ltr' | 'rtl';
  setLang: (lang: Language) => void;
  t: (key: TranslationKeys, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem('retac_lang');
    return saved === 'en' ? 'en' : 'ar';
  });

  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem('retac_lang', lang);
  }, [lang, dir]);

  const t = (key: TranslationKeys, values?: Record<string, string | number>): string => {
    let value: string = translations[lang][key];
    for (const [name, replacement] of Object.entries(values || {})) {
      value = value.replace(`{{${name}}}`, String(replacement));
    }
    return value;
  };

  return (
    <I18nContext.Provider value={{ lang, dir, setLang: setLangState, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
};
